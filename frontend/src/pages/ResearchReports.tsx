import { useState, type FormEvent } from 'react';
import { apiRequest, type Report } from '../api';
import { Card, Page } from '../components/ui/PageComponents';

export function ResearchReports() {
  const [reportId, setReportId] = useState('');
  const [report, setReport] = useState<Report | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);
  const load = async (event: FormEvent) => {
    event.preventDefault(); setError(null); setReport(null); setLoading(true);
    try { setReport(await apiRequest<Report>(`/report/${reportId.trim()}`)); }
    catch (cause) { setError(cause instanceof Error ? cause.message : 'Could not load report'); }
    finally { setLoading(false); }
  };
  return <Page title="Research Reports" subtitle="View reports generated by completed simulations and backtests" eyebrow="Research workspace">
    <Card title="Retrieve a workflow report" subtitle="GET /api/v1/report/{report_id}">
      <form onSubmit={load} className="flex flex-wrap items-end gap-3"><label className="text-sm">Report ID<input required value={reportId} onChange={e => setReportId(e.target.value)} className="mt-1 block w-96 max-w-full rounded bg-slate-800 p-2" placeholder="Paste report ID from a completed job" /></label>
        <button disabled={loading} className="rounded bg-lime-300 px-4 py-2 font-semibold text-slate-950">{loading ? 'Loading…' : 'Load report'}</button></form>
      {error && <p role="alert" className="mt-4 text-red-400">{error}</p>}
      {report && <div className="mt-5 rounded bg-slate-800 p-4"><h2 className="text-lg font-semibold">{report.title}</h2><p className="text-sm text-slate-400">Generated {new Date(report.generated_at).toLocaleString()}</p><p className="mt-3">{report.summary}</p><dl className="mt-4 grid gap-3 sm:grid-cols-2">{Object.entries(report.metrics).map(([key, value]) => <div key={key}><dt className="text-xs uppercase text-slate-400">{key.replaceAll('_', ' ')}</dt><dd className="mono">{value}</dd></div>)}</dl></div>}
    </Card>
  </Page>;
}
