-- TimescaleDB initialization script
-- This script runs when the TimescaleDB container starts for the first time

-- Enable TimescaleDB extension
CREATE EXTENSION IF NOT EXISTS timescaledb CASCADE;

-- Enable UUID extension for generating UUIDs
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- Enable citext for case-insensitive text
CREATE EXTENSION IF NOT EXISTS citext;

-- Create schemas for different modules
CREATE SCHEMA IF NOT EXISTS market_data;
CREATE SCHEMA IF NOT EXISTS portfolio;
CREATE SCHEMA IF NOT EXISTS analytics;
CREATE SCHEMA IF NOT EXISTS simulation;
CREATE SCHEMA IF NOT EXISTS risk;
CREATE SCHEMA IF NOT EXISTS decision;
CREATE SCHEMA IF NOT EXISTS validation;

-- Grant permissions to the metis user
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA public TO metis;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA market_data TO metis;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA portfolio TO metis;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA analytics TO metis;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA simulation TO metis;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA risk TO metis;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA decision TO metis;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA validation TO metis;

GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public TO metis;
GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA market_data TO metis;
GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA portfolio TO metis;
GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA analytics TO metis;
GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA simulation TO metis;
GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA risk TO metis;
GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA decision TO metis;
GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA validation TO metis;

-- Set default privileges for future objects
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO metis;
ALTER DEFAULT PRIVILEGES IN SCHEMA market_data GRANT ALL ON TABLES TO metis;
ALTER DEFAULT PRIVILEGES IN SCHEMA portfolio GRANT ALL ON TABLES TO metis;
ALTER DEFAULT PRIVILEGES IN SCHEMA analytics GRANT ALL ON TABLES TO metis;
ALTER DEFAULT PRIVILEGES IN SCHEMA simulation GRANT ALL ON TABLES TO metis;
ALTER DEFAULT PRIVILEGES IN SCHEMA risk GRANT ALL ON TABLES TO metis;
ALTER DEFAULT PRIVILEGES IN SCHEMA decision GRANT ALL ON TABLES TO metis;
ALTER DEFAULT PRIVILEGES IN SCHEMA validation GRANT ALL ON TABLES TO metis;

ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO metis;
ALTER DEFAULT PRIVILEGES IN SCHEMA market_data GRANT ALL ON SEQUENCES TO metis;
ALTER DEFAULT PRIVILEGES IN SCHEMA portfolio GRANT ALL ON SEQUENCES TO metis;
ALTER DEFAULT PRIVILEGES IN SCHEMA analytics GRANT ALL ON SEQUENCES TO metis;
ALTER DEFAULT PRIVILEGES IN SCHEMA simulation GRANT ALL ON SEQUENCES TO metis;
ALTER DEFAULT PRIVILEGES IN SCHEMA risk GRANT ALL ON SEQUENCES TO metis;
ALTER DEFAULT PRIVILEGES IN SCHEMA decision GRANT ALL ON SEQUENCES TO metis;
ALTER DEFAULT PRIVILEGES IN SCHEMA validation GRANT ALL ON SEQUENCES TO metis;

-- Log initialization
DO $$
BEGIN
    RAISE NOTICE 'TimescaleDB initialized for Project Métis';
END $$;